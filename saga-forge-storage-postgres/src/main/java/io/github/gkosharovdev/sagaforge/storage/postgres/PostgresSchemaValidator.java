package io.github.gkosharovdev.sagaforge.storage.postgres;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Comparator;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Pattern;
import javax.sql.DataSource;

/**
 * Checks a database against the schema a {@link SchemaVersion} needs, and finds which version a
 * database without Saga Forge's migration history is at. Reads only: every call runs in one
 * read-only transaction on the connection's {@code current_schema()}.
 *
 * <p>Tables and columns (type and nullability) are compared by name; primary keys, unique and
 * foreign keys by their columns; checks and indexes by their definition, so names given by hand or
 * generated by Postgres never matter. Missing or different tables, columns and constraints fail the
 * check; a missing index is a warning; anything extra is ignored, so an application may add its own
 * columns, tables and indexes.
 *
 * <pre>{@code
 * SchemaValidationReport report = new PostgresSchemaValidator(dataSource).validate();
 * if (!report.passed()) {
 *   throw SagaSchemaException.failedCheck(report);
 * }
 * }</pre>
 */
public final class PostgresSchemaValidator {

  private static final Pattern TABLE_NAME = Pattern.compile("[a-z_][a-z0-9_]{0,62}");

  private final DataSource dataSource;

  /**
   * @param dataSource the database to read; no connection is opened until a method is called
   */
  public PostgresSchemaValidator(DataSource dataSource) {
    this.dataSource = Objects.requireNonNull(dataSource, "dataSource");
  }

  /**
   * @return the check against {@link PostgresSchema#currentVersion()}
   * @throws UncheckedSqlException if the catalog cannot be read
   */
  public SchemaValidationReport validate() {
    return validate(PostgresSchema.currentVersion());
  }

  /**
   * @param expected the version to check against
   * @return every difference from that version
   * @throws UncheckedSqlException if the catalog cannot be read
   */
  public SchemaValidationReport validate(SchemaVersion expected) {
    SchemaSnapshot snapshot = SchemaSnapshot.load(expected);
    SchemaSnapshot found = read(snapshot.tables().keySet());
    return new SchemaValidationReport(expected, SchemaComparison.compare(snapshot, found));
  }

  /**
   * Finds the newest version whose check has no failure, trying the newest first: later versions
   * only add to earlier ones, so an older version may pass too.
   *
   * @return {@link SchemaDetection.Empty} when none of Saga Forge's tables exist, {@link
   *     SchemaDetection.Matched} with the newest passing version, or {@link
   *     SchemaDetection.Unmatched} with the report that has the fewest failures (the newer version
   *     on a tie)
   * @throws UncheckedSqlException if the catalog cannot be read
   */
  public SchemaDetection detectVersion() {
    List<SchemaVersion> newestFirst =
        PostgresSchema.versions().stream().sorted(Comparator.reverseOrder()).toList();
    List<SchemaSnapshot> snapshots = newestFirst.stream().map(SchemaSnapshot::load).toList();
    Set<String> allTables = new TreeSet<>();
    snapshots.forEach(snapshot -> allTables.addAll(snapshot.tables().keySet()));
    SchemaSnapshot found = read(allTables);
    if (found.tables().isEmpty()) {
      return new SchemaDetection.Empty();
    }
    SchemaValidationReport closest = null;
    for (int i = 0; i < newestFirst.size(); i++) {
      SchemaValidationReport report =
          new SchemaValidationReport(
              newestFirst.get(i), SchemaComparison.compare(snapshots.get(i), found));
      if (report.passed()) {
        return new SchemaDetection.Matched(newestFirst.get(i), report);
      }
      if (closest == null || report.failures().size() < closest.failures().size()) {
        closest = report;
      }
    }
    return new SchemaDetection.Unmatched(closest);
  }

  /**
   * Reads the newest successfully applied version from a Flyway history table, without Flyway. A
   * baseline row counts as applied.
   *
   * @param historyTable the history table's name, in {@code current_schema()}
   * @return the newest applied version, empty when the table does not exist or holds no version; a
   *     version newer than this jar knows is returned with the description {@code "newer than this
   *     release"}
   * @throws IllegalArgumentException if {@code historyTable} is not a plain lower-case SQL name
   * @throws UncheckedSqlException if the table cannot be read
   */
  public Optional<SchemaVersion> appliedVersion(String historyTable) {
    if (!TABLE_NAME.matcher(historyTable).matches()) {
      throw new IllegalArgumentException(
          "the history table name must be a lower-case SQL name, was " + historyTable);
    }
    return readOnly(
        "could not read " + historyTable,
        connection -> {
          if (!tableExists(connection, historyTable)) {
            return Optional.empty();
          }
          try (Statement statement = connection.createStatement();
              ResultSet rows =
                  statement.executeQuery(
                      "SELECT version FROM "
                          + historyTable
                          + " WHERE success AND version IS NOT NULL")) {
            int newest = 0;
            while (rows.next()) {
              newest = Math.max(newest, numeric(rows.getString(1)));
            }
            return newest == 0 ? Optional.empty() : Optional.of(known(newest));
          }
        });
  }

  private static boolean tableExists(Connection connection, String table) throws SQLException {
    try (PreparedStatement statement =
        connection.prepareStatement(
            "SELECT to_regclass(quote_ident(current_schema()) || '.' || ?) IS NOT NULL")) {
      statement.setString(1, table);
      try (ResultSet rows = statement.executeQuery()) {
        rows.next();
        return rows.getBoolean(1);
      }
    }
  }

  private static int numeric(String version) {
    try {
      return Integer.parseInt(version.strip());
    } catch (NumberFormatException e) {
      return 0;
    }
  }

  private static SchemaVersion known(int number) {
    return number > PostgresSchema.currentVersion().number()
        ? new SchemaVersion(number, "newer than this release")
        : SchemaVersion.of(number);
  }

  private SchemaSnapshot read(Set<String> tables) {
    return readOnly(
        "could not read Saga Forge's schema from pg_catalog",
        connection -> CatalogReader.read(connection, tables));
  }

  /**
   * Runs {@code work} in a read-only transaction, rolled back, restoring the connection's state.
   */
  private <T> T readOnly(String failure, SqlWork<T> work) {
    try (Connection connection = dataSource.getConnection()) {
      boolean autoCommit = connection.getAutoCommit();
      boolean readOnly = connection.isReadOnly();
      connection.setAutoCommit(false);
      connection.setReadOnly(true);
      try {
        return work.run(connection);
      } finally {
        connection.rollback();
        connection.setReadOnly(readOnly);
        connection.setAutoCommit(autoCommit);
      }
    } catch (SQLException e) {
      throw new UncheckedSqlException(failure, e);
    }
  }

  @FunctionalInterface
  private interface SqlWork<T> {
    T run(Connection connection) throws SQLException;
  }
}
